import { relations, sql } from "drizzle-orm";
import {
  pgTable,
  text,
  timestamp,
  boolean,
  uuid,
  index,
  check,
} from "drizzle-orm/pg-core";

import { empresa } from "@/modules/empresas/schema";

export const user = pgTable(
  "user",
  {
    id: uuid("id")
      .default(sql`pg_catalog.gen_random_uuid()`)
      .primaryKey(),
    name: text("name").notNull(),
    email: text("email").notNull().unique(),
    emailVerified: boolean("email_verified").default(false).notNull(),
    image: text("image"),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .defaultNow()
      .$onUpdate(() => /* @__PURE__ */ new Date())
      .notNull(),
    role: text("role"),
    banned: boolean("banned").default(false),
    banReason: text("ban_reason"),
    banExpires: timestamp("ban_expires", { withTimezone: true }),
    empresaId: uuid("empresa_id").references(() => empresa.id),
  },
  () => [
    // Administrador da plataforma não tem empresa; a dona sempre tem. coalesce: role nulo não passa.
    check(
      "user_role_empresa_check",
      sql`coalesce(role, '') in ('admin', 'user') and (role = 'admin' or empresa_id is not null)`,
    ),
  ],
);

